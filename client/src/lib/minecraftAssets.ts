import textures from "@/lib/minecraftTextures.json";

// Textures served from public/minecraft_assets (an extracted Minecraft resource pack)
export const MINECRAFT_TEXTURES_ROOT = "/minecraft_assets/minecraft_assets/assets/minecraft/textures";

const available = {
  item: new Set<string>(textures.item),
  block: new Set<string>(textures.block),
};

export type IconSource =
  // Flat sprite, as drawn for items (tools, ingots...)
  | { type: "item"; url: string }
  // Block drawn as an isometric cube, like in the Minecraft inventory
  | { type: "cube"; top: string; left: string; right: string };

// Identifiers that have no texture of their own, mapped to the item or block that best stands for them
const ALIASES: Record<string, { kind: "item" | "block"; name: string }> = {
  nether_portal: { kind: "block", name: "obsidian" },
  end_portal: { kind: "block", name: "end_portal_frame" },
  stronghold: { kind: "item", name: "ender_eye" },
  ender_dragon: { kind: "block", name: "dragon_egg" },
};

const blockUrl = (name: string) => `${MINECRAFT_TEXTURES_ROOT}/block/${name}.png`;

// First existing block texture among the candidates (null when none exists)
const firstBlock = (...names: string[]) => names.find((name) => available.block.has(name)) ?? null;

/**
 * Build the cube of a block from its faces: top (`_top`), front (`_front`) on the left face and side (`_side`)
 * on the right face, each falling back to the plain texture. Returns null when the block has no usable texture.
 */
const cubeOf = (name: string): IconSource | null => {
  const base = firstBlock(name, `${name}_side`, `${name}_front`, `${name}_top`);
  if (!base) return null;
  const top = firstBlock(`${name}_top`, `${name}_end`, base)!;
  const right = firstBlock(`${name}_side`, base)!;
  const left = firstBlock(`${name}_front`, `${name}_side`, base)!;
  return { type: "cube", top: blockUrl(top), left: blockUrl(left), right: blockUrl(right) };
};

/**
 * Find how to draw an item or block identifier: items are flat sprites, blocks are cubes.
 * The list of existing textures is generated by scripts/generate-minecraft-textures.mjs, so no URL is ever
 * requested without existing.
 * @returns The icon source, or null when the resource pack has none (the caller then shows a fallback)
 */
export const resolveIcon = (id: string): IconSource | null => {
  const alias = ALIASES[id];
  if (alias?.kind === "item") return { type: "item", url: `${MINECRAFT_TEXTURES_ROOT}/item/${alias.name}.png` };
  if (alias?.kind === "block") return cubeOf(alias.name);

  if (available.item.has(id)) return { type: "item", url: `${MINECRAFT_TEXTURES_ROOT}/item/${id}.png` };
  return cubeOf(id);
};
